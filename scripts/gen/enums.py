#!/usr/bin/env python3
"""Writes HealthCopy/Import/AppleNames.swift: the enum case names Apple's Health export uses
for category values, workout activity types and workout event types, with their raw values,
read from the HealthKit headers of the installed SDK."""
import re, sys, pathlib

headers = pathlib.Path(sys.argv[1])
out = pathlib.Path(sys.argv[2])

def enums(text, prefix):
    found = {}
    for m in re.finditer(r'typedef NS_ENUM\(NSU?Integer, (\w+)\)\s*\{(.*?)\}', text, re.S):
        name, body = m.group(1), m.group(2)
        if not name.startswith(prefix):
            continue
        body = re.sub(r'/\*.*?\*/', '', body, flags=re.S)
        body = re.sub(r'//[^\n]*', '', body)
        # Availability macros carry commas of their own.
        body = re.sub(r'\b[A-Z_]+\w*\((?:[^()]|\((?:[^()]|\([^()]*\))*\))*\)', '', body)
        value = -1
        for part in body.split(','):
            part = part.strip()
            mm = re.match(r'(HK\w+)', part)
            if not mm:
                continue
            case = mm.group(1)
            ev = re.search(r'=\s*(-?\d+)\s*$', part)
            ref = re.search(r'=\s*(HK\w+)\s*$', part)
            if ev:
                value = int(ev.group(1))
            elif ref and ref.group(1) in found:
                value = found[ref.group(1)]
            else:
                value += 1
            found[case] = value
    return found

text = "\n".join(p.read_text() for p in headers.glob("*.h"))
cats = enums(text, "HKCategoryValue")
acts = {k: v for k, v in enums(text, "HKWorkoutActivityType").items() if k.startswith("HKWorkoutActivityType")}
evs = {k: v for k, v in enums(text, "HKWorkoutEventType").items() if k.startswith("HKWorkoutEventType")}

def table(name, d):
    rows = "\n".join(f'        "{k}": {v},' for k, v in sorted(d.items()))
    return f"    static let {name}: [String: Int] = [\n{rows}\n    ]\n"

out.write_text(
    "// Generated by scripts/gen/enums.py from the HealthKit headers. Don't edit.\n\n"
    "/// Names Apple's Health export writes for enum values, and the raw values they stand for.\n"
    "enum AppleNames {\n" + table("categoryValues", cats) + "\n" + table("activityTypes", acts) + "\n" + table("eventTypes", evs) + "}\n")
print(len(cats), len(acts), len(evs))
